// Helper to render type icons based on monument type
export function MonumentTypeIcon({ type, size = 18, color = "currentColor", className = "" }) {
  switch (type) {
    case 'Stepwell':
      return <IconStepwell size={size} color={color} className={className} />
    case 'Temple':
      return <IconTemple size={size} color={color} className={className} />
    case 'Fort':
      return <IconFort size={size} color={color} className={className} />
    case 'Haveli':
      return <IconHaveli size={size} color={color} className={className} />
    case 'Colonial Building':
      return <IconColonial size={size} color={color} className={className} />
    case 'Monument':
    default:
      return <IconMonument size={size} color={color} className={className} />
  }
}
